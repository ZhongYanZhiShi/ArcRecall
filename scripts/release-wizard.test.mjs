test("远端 main 有新提交时不创建版本提交或标签", async (t) => {
  const f = fixture(t)
  f.write("remote-change.txt", "remote change")
  f.git(["add", "remote-change.txt"])
  f.git(["commit", "-m", "Remote change"])
  f.git(["push", "origin", "main"])
  // Move only this disposable fixture branch back to simulate a stale checkout.
  f.git(["switch", "--detach", f.initial])
  f.git(["branch", "--force", "main", f.initial])
  f.git(["switch", "main"])
  await assert.rejects(f.run(), /远端最新提交/)
  assert.equal(f.git(["rev-parse", "HEAD"]), f.initial)
  assert.equal(f.git(["tag", "--list"]), "")
  assert.equal(f.git(["status", "--porcelain"]), "")
})

test("检查期间出现被工作区掩盖的无关暂存修改也会停止提交", async (t) => {
  const f = fixture(t, {
    beforeCommand: (program, args, { git, write }) => {
      if (program !== "cargo" || args[0] !== "metadata") return
      write("src-tauri/src/lib.rs", "pub fn user_edit() {}\n")
      git(["add", "src-tauri/src/lib.rs"])
      write("src-tauri/src/lib.rs", "pub fn hello() {}\n")
    },
  })
  await assert.rejects(f.run(), /发布文件以外/)
  assert.equal(f.git(["rev-parse", "HEAD"]), f.initial)
  assert.match(f.git(["diff", "--cached"]), /user_edit/)
  assert.equal(f.published, 0)
})

test("重试时保留远端附注标签，缺少本地标签则取回原标签", async (t) => {
  const f = fixture(t, { answers: ["修复问题", ".", "y", "y"] })
  // Prepare the version without reaching the first push.
  for (const [file, content] of versionEdits(f.root, "0.1.2"))
    f.write(file, content)
  f.write(
    ".github/release-notes/v0.1.2.md",
    "# ArcRecall v0.1.2\n\n- 修复问题\n"
  )
  f.git(["add", "."])
  f.git(["commit", "-m", "Prepare version"])
  f.git(["tag", "-a", "v0.1.2", "-m", "Annotated release"])
  const tagObject = f.git(["rev-parse", "refs/tags/v0.1.2"])
  f.git(["push", "origin", "main", "v0.1.2"])
  f.git(["tag", "-d", "v0.1.2"])
  // Existing notes skip the notes prompts.
  await releaseWizard(
    { tag: "v0.1.2" },
    {
      root: f.root,
      platform: "win32",
      arch: "x64",
      env: {
        TAURI_UPDATER_PUBLIC_KEY: "fixture",
        TAURI_SIGNING_PRIVATE_KEY: "fixture",
      },
      ask: async () => "y",
      log: () => {},
      execute: (program, args, options) => {
        if (program === "gh")
          return args[1] === "user" ? "ZhongYanZhiShi" : "[[]]"
        if (program === "git" && args[0] === "remote")
          return "git@github.com:ZhongYanZhiShi/ArcRecall.git"
        if (program === "git")
          return execute(program, args, { ...options, capture: true })
        return ""
      },
      release: () => {},
    }
  )
  assert.equal(f.git(["rev-parse", "refs/tags/v0.1.2"]), tagObject)
})
