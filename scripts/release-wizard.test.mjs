test("未提交源码和错误分支在版本写入前停止", async (t) => {
  const f = fixture(t)
  f.write("unrelated.txt", "user work")
  await assert.rejects(f.run(), /未提交改动/)
  assert.equal(f.git(["rev-parse", "HEAD"]), f.initial)
  f.git(["add", "unrelated.txt"])
  f.git(["commit", "-m", "User work"])
  f.git(["switch", "-c", "feature"])
  await assert.rejects(f.run(), /main 分支/)
  assert.equal(f.published, 0)
})

