import assert from "node:assert/strict"
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import os from "node:os"
import path from "node:path"
import test from "node:test"

import { execute } from "./release-local.mjs"
import {
  compareVersions,
  releaseWizard,
  suggestedVersion,
  versionEdits,
} from "./release-wizard.mjs"

function fixture(t, overrides = {}) {
  const directory = mkdtempSync(path.join(os.tmpdir(), "arcrecall-wizard-"))
  const root = path.join(directory, "work")
  const remote = path.join(directory, "remote.git")
  mkdirSync(root)
  t.after(() => rmSync(directory, { recursive: true, force: true }))
  const write = (file, contents) => {
    const destination = path.join(root, file)
    mkdirSync(path.dirname(destination), { recursive: true })
    writeFileSync(destination, contents)
  }
  const git = (args) => execute("git", args, { cwd: root, capture: true })
  git(["init", "--initial-branch=main"])
  git(["config", "user.name", "Release Test"])
  git(["config", "user.email", "release-test@example.invalid"])
  git(["config", "commit.gpgsign", "false"])
  git(["config", "tag.gpgsign", "false"])
  git(["config", "core.hooksPath", path.join(directory, "no-hooks")])
  write("package.json", '{"version":"0.1.1","other":"unchanged"}\n')
  write("src-tauri/tauri.conf.json", '{"version":"0.1.1"}\n')
  write(
    "Cargo.toml",
    '[workspace]\nmembers = ["src-tauri", "crates/core"]\nresolver = "2"\n'
  )
  write(
    "src-tauri/Cargo.toml",
    '[package]\nname = "arc-recall-desktop"\nversion = "0.1.1"\nedition = "2024"\n'
  )
  write("src-tauri/src/lib.rs", "pub fn hello() {}\n")
  write(
    "crates/core/Cargo.toml",
    '[package]\nname = "arc-recall-core"\nversion = "0.1.0"\nedition = "2024"\n'
  )
  write("crates/core/src/lib.rs", "pub fn core() {}\n")
  write(
    "Cargo.lock",
    '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "arc-recall-core"\nversion = "0.1.0"\n\n[[package]]\nname = "arc-recall-desktop"\nversion = "0.1.1"\n'
  )
  git(["add", "."])
  git(["commit", "-m", "Initial fixture"])
  git(["init", "--bare", remote])
  git(["remote", "add", "origin", remote])
  git(["push", "origin", "main"])
  const initial = git(["rev-parse", "HEAD"])
  const calls = []
  const answers = overrides.answers ?? [
    "修复导入失败",
    "改善压缩速度",
    ".",
    "y",
  ]
  let published = 0
  const releaseOptions = []
  const messages = []
  let confirmHook = overrides.confirmHook
  const command = (program, args, options) => {
    calls.push({ program, args })
    overrides.beforeCommand?.(program, args, { git, write })
    if (overrides.fail?.(program, args)) throw new Error("simulated failure")
    if (program === "gh") {
      if (args[1] === "user") return overrides.login ?? "ZhongYanZhiShi"
      return JSON.stringify([overrides.draft ? [overrides.draft] : []])
    }
    if (program === "git") {
      if (args[0] === "remote" && args[1] === "get-url")
        return "git@github.com:ZhongYanZhiShi/ArcRecall.git"
      return execute(program, args, { ...options, capture: true })
    }
    if (program === "cargo")
      return execute(program, args, { ...options, capture: true })
    return ""
  }
  return {
    root,
    git,
    write,
    calls,
    initial,
    releaseOptions,
    messages,
    get published() {
      return published
    },
    run: (options = { tag: "v0.1.2" }) =>
      releaseWizard(options, {
        root,
        execute: command,
        platform: "win32",
        arch: "x64",
        env: {
          TAURI_UPDATER_PUBLIC_KEY: "fixture-public",
          TAURI_SIGNING_PRIVATE_KEY: "fixture-private",
        },
        log: (message) => messages.push(message),
        ask: async (question) => {
          if (question.startsWith("开始执行") && confirmHook) {
            confirmHook({ git, write })
            confirmHook = undefined
          }
          assert.ok(answers.length, `Unexpected prompt: ${question}`)
          return answers.shift()
        },
        release: (options) => {
          const { tag } = options
          releaseOptions.push(options)
          published++
          const head = git(["rev-parse", "HEAD"])
          assert.equal(git(["status", "--porcelain"]), "")
          assert.equal(git(["rev-parse", `refs/tags/${tag}^{commit}`]), head)
          assert.ok(
            git(["ls-remote", "origin", `refs/tags/${tag}`]).startsWith(head)
          )
          assert.ok(
            git(["ls-remote", "origin", "refs/heads/main"]).startsWith(head)
          )
          if (overrides.buildFailure) throw new Error("build failed")
        },
      }),
  }
}

test("默认递增补丁版本，预发布默认转同版本正式版", () => {
  assert.equal(suggestedVersion("0.1.1"), "0.1.2")
  assert.equal(suggestedVersion("1.0.0-beta.2"), "1.0.0")
  const ordered = [
    "0.9.9",
    "1.0.0-alpha",
    "1.0.0-alpha.2",
    "1.0.0-alpha.10",
    "1.0.0-beta",
    "1.0.0-beta.1",
    "1.0.0",
    "1.0.1",
    "2.0.0",
  ]
  for (let i = 1; i < ordered.length; i++) {
    assert.equal(compareVersions(ordered[i - 1], ordered[i]), -1)
    assert.equal(compareVersions(ordered[i], ordered[i - 1]), 1)
  }
  assert.equal(compareVersions("1.0.0-beta.1", "1.0.0-beta.1"), 0)
})

test("回车采用建议版本，提交并推送 main 和标签，默认交给草稿发布器", async (t) => {
  const f = fixture(t, {
    answers: ["", "修复导入失败", "改善压缩速度", ".", "y"],
  })
  await f.run({})
  assert.equal(f.published, 1)
  assert.equal(f.releaseOptions[0].publish, false)
  assert.ok(f.messages.some((message) => message.includes("（草稿）")))
  assert.equal(
    JSON.parse(readFileSync(path.join(f.root, "package.json"))).version,
    "0.1.2"
  )
  assert.match(
    readFileSync(path.join(f.root, "Cargo.lock"), "utf8"),
    /name = "arc-recall-core"\nversion = "0.1.0"/
  )
  assert.match(
    readFileSync(path.join(f.root, "Cargo.lock"), "utf8"),
    /name = "arc-recall-desktop"\nversion = "0.1.2"/
  )
  assert.equal(
    readFileSync(path.join(f.root, ".github/release-notes/v0.1.2.md"), "utf8"),
    "- 修复导入失败\n- 改善压缩速度\n"
  )
  assert.equal(f.git(["rev-list", "--count", "HEAD"]), "2")
  assert.deepEqual(
    f.calls.find(({ program, args }) => program === "git" && args[0] === "push")
      .args,
    [
      "push",
      "--atomic",
      "origin",
      "HEAD:refs/heads/main",
      "refs/tags/v0.1.2:refs/tags/v0.1.2",
    ]
  )
})

